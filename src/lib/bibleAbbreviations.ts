export function resolveBookToken(token: string): (typeof BIBLE_BOOKS)[number] | undefined {
  const raw = token.replace(/\./g, ' ').replace(/\s+/g, ' ').trim()
  const lower = raw.toLowerCase()
  const compact = lower.replace(/\s+/g, '')
  const fromAbbr = BIBLE_ABBREVIATIONS[compact]
  if (fromAbbr) {
    return BIBLE_BOOKS.find((b) => b.name === fromAbbr)
  }
  return BIBLE_BOOKS.find(
    (b) =>
      b.name.toLowerCase() === lower ||
      (b.short && b.short.toLowerCase() === lower) ||
      b.name.toLowerCase().startsWith(lower),
  )
}

